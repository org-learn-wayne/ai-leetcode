package hackerrank;

import static org.junit.jupiter.api.Assertions.assertEquals;
import org.junit.jupiter.api.Test;

public class SamSubstringsTest {

    @Test
    void test1() {
        assertEquals(1+6+16, SamSubstrings.substrings("16"));
        assertEquals(
            3+8+5+2+1+
            38+85+52+21+
            385+852+521+
            3852+8521+
            38521
            , SamSubstrings.substrings("38521"));
        assertEquals(
            (
                8+4+3+8+5+2+1+
                84+43+38+85+52+21+
                843+438+385+852+521+
                (8438+4385+3852+8521) % 1000000007 +
                (84385+43852+38521) % 1000000007 +
                (843852+438521) % 1000000007 +
                (8438521) % 1000000007 
            ) % 1000000007 
            , SamSubstrings.substrings("8438521"));
        assertEquals(
            (
                9+7+2+6+9+8+4+3+8+5+2+1+
                97+72+26+69+98+84+43+38+85+52+21+
                972+726+269+698+984+843+438+385+852+521+
                (9726+7269+2698+6984+9843+8438+4385+3852+8521) % 1000000007 +
                (97269+72698+26984+69843+98438+84385+43852+38521) % 1000000007 +
                (972698+726984+269843+698438+984385+843852+438521) % 1000000007 +
                (9726984+7269843+2698438+6984385+9843852+8438521) % 1000000007 +
                (97269843+72698438+26984385+69843852+98438521) % 1000000007 +
                (972698438+726984385+269843852+698438521) % 1000000007 +
                (9726984385L+7269843852L+2698438521L) % 1000000007 +
                (97269843852L+72698438521L) % 1000000007 +
                (972698438521L) % 1000000007
            ) % 1000000007 
            , SamSubstrings.substrings("972698438521"));
    }
}